/**
 * Generates same-origin site-search proxy config for the Community embed.
 *
 * - `public/embed/wl-site-search-config.js` — anon key only (no functions URL)
 * - Ensures `public/_redirects` has `/api/site-search` → Edge proxy
 *
 * Run via `predev` / `prebuild`. Requires NEXT_PUBLIC_SUPABASE_URL + ANON_KEY
 * (from env or `.env.local`).
 */
const fs = require("fs")
const path = require("path")

const root = path.join(__dirname, "..")
const envPath = path.join(root, ".env.local")

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return
  const text = fs.readFileSync(filePath, "utf8")
  for (const line of text.split("\n")) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const eq = trimmed.indexOf("=")
    if (eq <= 0) continue
    const key = trimmed.slice(0, eq).trim()
    let val = trimmed.slice(eq + 1).trim()
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1)
    }
    if (process.env[key] == null || process.env[key] === "") {
      process.env[key] = val
    }
  }
}

loadEnvFile(envPath)

const supabaseUrl = (process.env.NEXT_PUBLIC_SUPABASE_URL || "")
  .trim()
  .replace(/\/$/, "")
const anonKey = (process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || "").trim()

if (!supabaseUrl || !anonKey) {
  console.error(
    "[generate-site-search-proxy] Missing NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_ANON_KEY",
  )
  process.exit(1)
}

const configPath = path.join(root, "public/embed/wl-site-search-config.js")
const configJs = `/* Generated by scripts/generate-site-search-proxy.cjs — do not edit. */
window.__WL_SITE_SEARCH_CONFIG__ = {
  /* Same-origin path only; Netlify / next.dev rewrite to Edge. */
  path: "/api/site-search",
  anonKey: ${JSON.stringify(anonKey)},
};
`

fs.mkdirSync(path.dirname(configPath), { recursive: true })
fs.writeFileSync(configPath, configJs)

const redirectsPath = path.join(root, "public/_redirects")
const markerStart = "# BEGIN site-search-proxy"
const markerEnd = "# END site-search-proxy"
const proxyBlock = [
  markerStart,
  `# Same-origin proxy so embeds never call *.supabase.co directly.`,
  `/api/site-search  ${supabaseUrl}/functions/v1/site-search  200!`,
  markerEnd,
].join("\n")

let redirects = fs.existsSync(redirectsPath)
  ? fs.readFileSync(redirectsPath, "utf8")
  : ""

if (redirects.includes(markerStart) && redirects.includes(markerEnd)) {
  redirects = redirects.replace(
    new RegExp(`${markerStart}[\\s\\S]*?${markerEnd}`, "m"),
    proxyBlock,
  )
} else {
  redirects = `${proxyBlock}\n\n${redirects.replace(/^\uFEFF/, "")}`
}

fs.writeFileSync(redirectsPath, redirects)

console.log(
  "[generate-site-search-proxy] Wrote embed config + /api/site-search redirect",
)
